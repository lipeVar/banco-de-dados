;
USE AULA15
;
CREATE TABLE ITENSPEDIDO (
	ID_ITEMPEDIDO INT AUTO_INCREMENT PRIMARY KEY,
    DESCRI_PRODUTO VARCHAR(100),
    QUANTIDADE INT,
    VALOR_UNITARIO DECIMAL(7, 2)
)
;

CREATE TABLE auditoria (
	ACAO VARCHAR(30),
	DATA DATETIME
)


DELIMITER @

CREATE TRIGGER auditar_insercao
AFTER INSERT ON ITENSPEDIDO
FOR EACH ROW
BEGIN
    INSERT INTO auditoria (acao, data)
    VALUES ('Novo pedido inserido', NOW());
END @

DELIMITER ;

