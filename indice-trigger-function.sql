DELIMITER $$

CREATE FUNCTION calcular_total_item(p_id INT)
RETURNS DECIMAL(10,2)
DETERMINISTIC
BEGIN
    DECLARE total DECIMAL(10,2);

    SELECT QUANTIDADE * VALOR_UNITARIO
    INTO total
    FROM ITENSPEDIDO
    WHERE ID_ITEMPEDIDO = p_id;

    RETURN total;
END $$

DELIMITER ;

SELECT DESCRI_PRODUTO, CALCULAR_TOTAL_ITEM(ID_ITEMPEDIDO) AS TOTAL_DO_ITEM
FROM ITENSPEDIDO