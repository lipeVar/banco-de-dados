-- REALIZE UMA TRANSFERENCIA DE ENTRE OS DOIS ALUNOS, 1000 DE JOAO PARA MARIA E 2000 REAIS DE MARIA PARA JOAO

CREATE PROCEDURE USP_TRANSFERENCIA
	@CONTA_ORIGEM INT,
	@CONTA_DESTINO INT,
	@VALOR DECIMAL(10,2)
AS 
BEGIN
	BEGIN TRANSACTION
	IF((SELECT SALDO FROM CONTA WHERE CONTAID = @CONTA_ORIGEM) >= @VALOR)
		BEGIN
			UPDATE CONTA
			SET SALDO = SALDO - @VALOR
			WHERE CONTAID = @CONTA_ORIGEM;

			UPDATE CONTA
			SET SALDO = SALDO + @VALOR
			WHERE CONTAID = @CONTA_DESTINO;

			COMMIT TRAN
			PRINT 'SALDO ATUALIZADO COM SUCESSO'
		END
	ELSE
		BEGIN
			PRINT 'SALDO INSUFICIENTE';
			ROLLBACK TRANSACTION
		END
END
-- TRANSFERENCIA DE 1000 PARA MARIA
EXEC USP_TRANSFERENCIA 10, 20, 1000;
SELECT * FROM CONTA;
-- TRANSFERENCIA DE 2000 PARA JOAO
EXEC USP_TRANSFERENCIA 20, 10, 20000;
SELECT * FROM CONTA;
-- TRANSFERENCIA PARA NINGUEM
EXEC USP_TRANSFERENCIA 20, 50, 1000;
SELECT * FROM CONTA;
GO

