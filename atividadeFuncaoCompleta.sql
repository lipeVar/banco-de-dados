CREATE FUNCTION FN_PROJETOS_POR_FUNCIONARIO (@CPF CHAR(11))
RETURNS TABLE
AS
RETURN(
	SELECT P.Projnome
	FROM PROJETO AS P
	INNER JOIN TRABALHA_EM T ON P.Projnumero = T.Pnr
	WHERE T.Fcpf = @CPF
);
GO
