CREATE FUNCTION fn_QtdProjetosFuncionario (@Cpf CHAR(11))
RETURNS INT
AS
BEGIN
    DECLARE @Quantidade INT;

    SELECT @Quantidade = COUNT(Pnr)
    FROM TRABALHA_EM
    WHERE Fcpf = @Cpf;

    RETURN @Quantidade;
END;
GO

