CREATE FUNCTION FN_ANOAPOSENTADORIA (@DataNascimento DATE)
RETURNS INT
AS
BEGIN
    RETURN YEAR(DATEADD(YEAR, 65, @DataNascimento));
END;
GO

SELECT 
    Pnome AS Nome,
    Datanasc AS Data_de_Nascimento,
    dbo.fn_AnoAposentadoria(Datanasc) AS Ano_Aposentadoria
FROM FUNCIONARIO;
GO

