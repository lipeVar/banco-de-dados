-- CRIAR UMA TABELA LOG
CREATE TABLE LOG_SAL_FUNCIONARIO
(
	LOG_ID INT IDENTITY(100, 1) PRIMARY KEY,
	CPF CHAR(11),
	OPERACAO VARCHAR(10),
	DATA_HORA DATETIME DEFAULT GETDATE()
)
GO

--TRIGGER DE INSERT
CREATE TRIGGER TRG_FOR_INSERT_FUNCIONARIO
on FUNCIONARIO
FOR INSERT
AS
BEGIN
	INSERT INTO LOG_SAL_FUNCIONARIO (CPF, OPERACAO)
	SELECT CPF, 'INSERT'
	FROM inserted
END
GO
--TRIGGER UPDATE
CREATE TRIGGER TRG_FOR_UPDATE_FUNCIONARIO
on FUNCIONARIO
FOR UPDATE
AS
BEGIN
	INSERT INTO LOG_SAL_FUNCIONARIO (CPF, OPERACAO)
	SELECT CPF, 'UPDATE'
	FROM inserted
END

GO
-- TRIGGER DELETE
CREATE TRIGGER TRG_FOR_DELETE_FUNCIONARIO
on FUNCIONARIO
FOR DELETE
AS
BEGIN
	INSERT INTO LOG_SAL_FUNCIONARIO (CPF, OPERACAO)
	SELECT CPF, 'DELETE'
	FROM deleted
END
GO

