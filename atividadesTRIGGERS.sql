CREATE OR ALTER TRIGGER trg_nao_insere_dp_com_mesmo_nome
ON DEPARTAMENTO
INSTEAD OF INSERT
AS
BEGIN
	DECLARE @nome VARCHAR(40), @numero AS INT;
	SELECT @nome = I.Dnome, @numero = I.Dnumero 
	FROM inserted AS I;
	IF EXISTS(
		SELECT 1 
		FROM DEPARTAMENTO 
		WHERE Dnome = @nome)

		RAISERROR('JA EXISTE ESSE DEPARTAMENTO',16, 1) -- aviso + severidade do erro  + estado
	ELSE
		INSERT INTO DEPARTAMENTO(Dnome, Dnumero, Cpf_gerente, Data_inicio_gerente)
		SELECT I.Dnome, I.Dnumero, I.Cpf_gerente, I.Data_inicio_gerente
		FROM inserted AS I;
END;
GO

